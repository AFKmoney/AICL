"""
AICL Autonomous Compilation System — Self-Writing, Self-Validating Code

The central thesis: a compiler that cannot explain why it generated a line
should not generate it. This module extends that thesis to its logical
conclusion: a compiler that can diagnose its own failures, fix its own
specifications, learn new patterns, and validate its own output — all
while preserving the No-Orphan Property.

The Autonomous Compilation Loop:
    SPEC → COMPILE → VERIFY → TEST → DIAGNOSE → FIX → RECOMPILE
                     ↑                                      │
                     └──────────────────────────────────────┘

Every iteration of the loop preserves the provenance chain. Every fix
is recorded. Every learned pattern is tracked. The loop converges when:
    1. Spec verification passes (completeness, coherence, satisfaction)
    2. Audit coverage = 1.0 (no orphans)
    3. All generated tests pass
    4. No fallback compilations remain
    5. Improvement score converges (delta < threshold)

New ProvenanceTypes added by this module:
    - AI_GENERATION: Code generated by AI-assisted fallback
    - SELF_HEALING: Code fixed by autonomous diagnosis
    - PATTERN_LEARNED: New pattern learned from unmatched actions
    - SPEC_EVOLVED: Specification modified by autonomous evolution

Usage:
    aicl evolve <source.aicl> [--max-iterations 10] [--no-ai]
    aicl evolve <source.aicl> --watch  # continuous mode
"""

